import assert from "node:assert/strict";
import {summary,validateTask,filterTasks,dayNumber,addDays,todayInShanghai,demoProject,taskBlockers,safeLink} from "../public/assets/planner-model.js";
const {project,members,tasks}=demoProject("2026-10-16");
const task=tasks[0],validate=(t,list=tasks)=>validateTask(t,list,project.phases,members);
assert.equal(todayInShanghai(new Date("2026-10-15T17:00:00Z")),"2026-10-16","Dates follow Shanghai, not host time");
assert.ok(Number.isNaN(dayNumber("2026-02-30")),"Reject normalized but invalid calendar dates");
assert.equal(addDays("2026-03-08",1),"2026-03-09","Calendar arithmetic avoids daylight-saving shifts");
assert.equal(summary([{...task,effort:1,progress:100},{...task,id:"b",effort:9,progress:0},{...task,id:"c",kind:"milestone",effort:999,progress:100}]).progress,10,"Weight by effort and exclude milestones");
assert.equal(summary([{...task,archived:true}]).total,0,"Archived tasks leave the aggregate");
assert.equal(summary([]).progress,0,"Empty projects are valid");
assert.equal(validate({...task,starts:"2026-10-20",ends:"2026-10-19"}),"结束日期不能早于开始日期。");
assert.equal(validate({...task,ends:null}),"开始和结束日期请一起填写，也可以都不填。");
assert.match(validate({...task,dependencies:[tasks[1].id]}),/循环/,"Reject indirect dependency cycles");
assert.match(validate({...task,assignee_id:"outsider"}),/成员/,"Only project members can be assigned");
assert.match(validate({...task,archived:true}),/仍依赖/,"Archiving cannot silently sever dependencies");
assert.equal(validate({...task,starts:null,ends:null}),"","Unscheduled tasks are allowed");
assert.equal(taskBlockers(tasks[4],tasks).length,3);
assert.equal(filterTasks(tasks,{person:"unassigned"})[0].id,"demo-4");
assert.equal(filterTasks(tasks,{query:"交互"}).length,2);
assert.equal(safeLink("javascript:alert(1)"),"");
assert.equal(safeLink("https://example.com/"),"https://example.com/");
console.log("Planner model: date, progress, filter, assignment and dependency checks passed.");
